// One-off generator: dump the curated tables from Supabase into docs/seed.sql.
//
// Not part of the app. Kept so the snapshot can be regenerated after a harvest:
//   node scripts/export-seed.mjs   (with SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY set)
import { createClient } from "@supabase/supabase-js";
import { writeFileSync } from "node:fs";

const client = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

// Insert order matters: referenced tables first.
const TABLES = [
  { name: "ward_offices", pk: "id" },
  { name: "bank_merger_map", pk: "old_bank_code" },
  { name: "empaneled_hospitals", pk: "id" },
  { name: "schemes", pk: "slug" },
  { name: "scheme_documents", pk: "id" },
  { name: "scheme_faqs", pk: "id" },
  { name: "peer_intel_reviews", pk: "id" }
];

// Derived / non-portable columns. embedding is a pgvector value that the app
// does not require (retrieval falls back to lexical ranking).
const SKIP = new Set(["embedding"]);
// source_documents is not exported, so FK pointers to it are nulled to keep the seed self-contained.
const NULLIFY = new Set(["source_doc_id"]);

function literal(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (typeof value === "number") return String(value);
  if (typeof value === "object") return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

const out = [];
out.push("-- NagrikSetu data snapshot.");
out.push("--");
out.push("-- Generated by scripts/export-seed.mjs from the reference project.");
out.push("-- Apply AFTER docs/SUPABASE_SETUP.sql and docs/migrations/*.sql, in filename order.");
out.push("--");
out.push("-- The whole file is idempotent: every statement uses ON CONFLICT DO NOTHING,");
out.push("-- so re-running it will not duplicate or overwrite existing rows.");
out.push("");
out.push("BEGIN;");

const counts = [];
for (const { name, pk } of TABLES) {
  const { data, error } = await client.from(name).select("*").order(pk, { ascending: true });
  if (error) {
    out.push(`-- ${name}: SKIPPED (${error.message})`);
    counts.push(`${name}: skipped`);
    continue;
  }
  if (!data?.length) {
    out.push(`-- ${name}: empty, nothing to seed`);
    counts.push(`${name}: 0`);
    continue;
  }

  const columns = Object.keys(data[0]).filter((c) => !SKIP.has(c));
  out.push("");
  out.push(`-- ${name} (${data.length} rows)`);
  out.push(`INSERT INTO public.${name} (${columns.join(", ")})`);
  out.push("VALUES");
  const rows = data.map(
    (row) => `  (${columns.map((c) => literal(NULLIFY.has(c) ? null : row[c])).join(", ")})`
  );
  out.push(rows.join(",\n"));
  out.push("ON CONFLICT DO NOTHING;");
  counts.push(`${name}: ${data.length}`);
}

out.push("");
out.push("COMMIT;");
out.push("");

writeFileSync(new URL("../docs/seed.sql", import.meta.url), out.join("\n"), "utf8");
console.log("wrote docs/seed.sql");
for (const line of counts) console.log("  ", line);
